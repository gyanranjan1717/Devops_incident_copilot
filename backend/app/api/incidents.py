@router.post("/webhook")
async def receive_incident_webhook(request: Request):
    """
    User Method 2: Public webhook receiver.
    Accepts incoming incident alerts from external monitoring platforms
    (Sentry, Datadog, BetterStack, Cloudflare, PagerDuty, or custom curl).
    Automatically triages the alert and stores in recent webhook feed.
    """
    try:
        payload = await request.json()
    except Exception:
        raw_body = await request.body()
        payload = {"raw_message": raw_body.decode(errors="ignore")}

    # Extract human-readable summary
    alert_text = (
        payload.get("message")
        or payload.get("text")
        or payload.get("description")
        or payload.get("error")
        or payload.get("alert")
        or json.dumps(payload, indent=2)
    )

    source = request.headers.get("x-webhook-source") or request.query_params.get("source") or "External Webhook"
    incident_id = f"wh-{uuid.uuid4().hex[:8]}"

    # Execute SRE triage
    triage = await orchestrator.triage_incident(
        alert_payload=str(alert_text),
        provider="gemini",
        model_name="gemini-1.5-pro"
    )

    record = {
        "id": incident_id,
        "source": source,
        "timestamp": datetime.datetime.utcnow().isoformat() + "Z",
        "payload": payload,
        "alert_text": alert_text,
        "triage_result": triage
    }

    # Store in recent feed
    RECENT_WEBHOOKS.insert(0, record)
    if len(RECENT_WEBHOOKS) > 20:
        RECENT_WEBHOOKS.pop()

    return {
        "status": "received_and_triaged",
        "incident_id": incident_id,
        "source": source,
        "triage_result": triage
    }

@router.get("/webhooks/recent")
def get_recent_webhooks():
    """Returns recently ingested webhook incidents."""
    return {"webhooks": RECENT_WEBHOOKS}

